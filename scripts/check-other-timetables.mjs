import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const snapshot = JSON.parse(await readFile(new URL('../public/timetable-snapshot.json', import.meta.url), 'utf8'));
const row = snapshot.timetable[0];
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, serviceWorkers: 'block' });
  await context.addInitScript(({ snapshot, row }) => {
    if (localStorage.getItem('seeded')) return;
    localStorage.setItem('seeded', 'true');
    localStorage.setItem('cachedTimetableData', JSON.stringify({ data: snapshot, at: Date.now() }));
    localStorage.setItem('selectedClasses_main', JSON.stringify([`${row.Course} - ${row.Section}`]));
  }, { snapshot, row });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.route('**/api/data', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: '{}' }));
  await page.route('**/api/auth-session', (route) => route.fulfill({ contentType: 'application/json', body: '{"user":null}' }));
  await page.goto('http://127.0.0.1:5173');
  await page.getByRole('region', { name: 'Sign in with Google' }).waitFor();
  const warning = await page.locator('.schedule-warning').boundingBox();
  const install = await page.locator('.persistent-install').boundingBox();
  const login = await page.getByRole('region', { name: 'Sign in with Google' }).boundingBox();
  assert.ok(warning.y < install.y && install.y < login.y);
  assert.equal(await page.locator('.persistent-install').evaluate((element) => getComputedStyle(element).position), 'static');
  await page.getByRole('button', { name: 'View other timetables', exact: true }).click();
  assert.equal(await page.locator('.other-profile').count(), 1);
  assert.equal(await page.locator('.other-profile span').count(), 0);
  await page.getByRole('button', { name: 'Add another timetable', exact: true }).click();
  assert.equal(await page.getByRole('dialog').locator('input').count(), 1);
  await page.getByLabel('Timetable name', { exact: true }).fill('Ali');
  await page.getByRole('button', { name: 'Create timetable', exact: true }).click();
  await page.getByRole('heading', { name: 'Ali', exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('selectedClasses'))), []);
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('selectedClasses_main'))), [`${row.Course} - ${row.Section}`]);
  await page.getByRole('tab', { name: 'Teacher', exact: true }).click();
  await page.getByRole('combobox', { name: 'Search instructors' }).fill(row.Instructor);
  await page.locator('.option-row-sync').filter({ hasText: row.Instructor }).first().click();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  const before = await page.evaluate(() => [localStorage.getItem('selectedClasses'), localStorage.getItem('linkedSync')]);
  await page.getByRole('button', { name: 'Back to my timetable', exact: true }).click();
  await page.getByRole('button', { name: 'View other timetables', exact: true }).click();
  await page.getByRole('button', { name: 'Rename Ali', exact: true }).click();
  assert.equal(await page.getByRole('dialog').locator('input').count(), 1);
  await page.getByLabel('Timetable name', { exact: true }).fill('Ali renamed');
  await page.getByRole('button', { name: 'Save name', exact: true }).click();
  await page.getByRole('button', { name: 'Ali renamed', exact: true }).waitFor();
  assert.deepEqual(await page.evaluate(() => [localStorage.getItem('selectedClasses'), localStorage.getItem('linkedSync')]), before);
  await page.getByRole('button', { name: 'Ali renamed', exact: true }).click();
  await page.reload();
  await page.getByRole('heading', { name: 'Ali renamed', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Install app', exact: true }).click();
  await page.getByRole('dialog', { name: 'Install FAST Timetable' }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.persistent-install').isVisible(), true);
  await page.evaluate(() => window.dispatchEvent(new Event('appinstalled')));
  await page.waitForFunction(() => !document.querySelector('.persistent-install'));
  assert.equal(await page.locator('.schedule-warning').isVisible(), true);
  await page.reload();
  await page.getByRole('heading', { name: 'Ali renamed', exact: true }).waitFor();
  assert.equal(await page.locator('.persistent-install').count(), 0);
  const disclaimer = page.getByRole('button', { name: 'Schedule disclaimer', exact: true });
  assert.equal(await disclaimer.getAttribute('aria-expanded'), 'true');
  await disclaimer.click();
  assert.equal(await page.locator('#schedule-warning-text').isVisible(), false);
  await page.reload();
  await page.getByRole('heading', { name: 'Ali renamed', exact: true }).waitFor();
  assert.equal(await disclaimer.getAttribute('aria-expanded'), 'true');
  await page.getByRole('button', { name: 'Back to my timetable', exact: true }).click();
  await page.getByRole('heading', { name: 'My timetable', exact: true }).waitFor();
  await page.getByRole('button', { name: 'View other timetables', exact: true }).click();
  await page.getByRole('button', { name: 'Delete Ali renamed', exact: true }).click();
  await page.getByRole('button', { name: 'Cancel deletion', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Ali renamed', exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Delete Ali renamed', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm delete timetable', exact: true }).click();
  assert.equal(await page.locator('.other-profile').count(), 1);
  assert.equal(await page.evaluate(() => localStorage.getItem('linkedSync')), null);
  assert.equal(await page.evaluate(() => localStorage.getItem('selectedClasses')), null);
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('selectedClasses_main'))), [`${row.Course} - ${row.Section}`]);
  await page.keyboard.press('Escape');
  await page.evaluate(() => {
    localStorage.setItem('timetableProfileNames', JSON.stringify(Object.fromEntries(Array.from({ length: 10 }, (_, index) => [index + 1, `Friend ${index + 1}`]))));
    localStorage.setItem('selectedClasses_10', localStorage.getItem('selectedClasses_main'));
  });
  await page.reload();
  await page.getByRole('button', { name: 'View other timetables', exact: true }).click();
  assert.equal(await page.locator('.other-profile').count(), 11);
  assert.equal(await page.getByRole('button', { name: 'Add another timetable' }).isDisabled(), true);
  await page.getByRole('button', { name: 'Friend 10', exact: true }).click();
  await page.getByRole('heading', { name: 'Friend 10', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: 'Friend 10', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Back to my timetable' }).click();
  await page.getByRole('button', { name: 'View other timetables' }).click();
  await page.getByRole('button', { name: 'Delete Friend 10', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm delete timetable' }).click();
  assert.equal(await page.getByRole('button', { name: 'Add another timetable' }).isEnabled(), true);
  assert.deepEqual(errors, []);
  console.log('Passed: warning/install/login order, name-only empty creation, clean list, rename preserves classes and teacher sync, reload, install help and success.');
} finally { await browser.close(); }
